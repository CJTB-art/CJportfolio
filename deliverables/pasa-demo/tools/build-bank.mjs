#!/usr/bin/env node
// Builds the app's Math Major data files from the converted bank. READ-ONLY on tools/out inputs.
// Usage: node tools/build-bank.mjs
// In : tools/out/bank-math.converted.json, topic-map.json, review-queue.json
// Out: src/lib/data/math-major/<topic-slug>.json (one per TOS topic), index.json (counts only),
//      src/lib/data/id-map.json (only if a mapping is PROVEN),
//      tools/out/unmapped-topics.json, unmapped-ids.json, bank-status-report.json
// Only the status field differs between rows; question text and answer keys are never edited here.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import {
  effective, flagsFor, applyDuplicates, assignIds, buildIdMap, statusOf, slug, mapBloom, mapDifficulty, SOURCE,
} from './lib/bank-build.js';

await import('./test-build-bank.mjs'); // edge-case asserts; a failure stops the build

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.join(HERE, '..');
const OUT = path.join(HERE, 'out');
const DATA = path.join(ROOT, 'src', 'lib', 'data');
const DIR = path.join(DATA, 'math-major');
const readJson = (p) => JSON.parse(fs.readFileSync(p, 'utf8'));
const bank = readJson(path.join(OUT, 'bank-math.converted.json'));
const topicMap = readJson(path.join(OUT, 'topic-map.json'));
const queue = readJson(path.join(OUT, 'review-queue.json'));
const TOS = topicMap.tosMathTopics; // [{ code, group, name }] in TOS order
const tosByName = new Map(TOS.map((t) => [t.name, t]));
const inc = (o, k, n = 1) => { o[k] = (o[k] || 0) + n; };

// converter flags -> review. Key = id + converted stem, because ids are not unique in this bank.
const queued = new Set(queue.items.map((i) => `${i.id}\u0000${i.after?.question}`));

// ---- 1. map every converted row; OUT_OF_TOS / UNMAPPED are dropped, not written to the app
const recs = [];
const dropped = { items: [], byTarget: {} };
let topicMapDisagrees = 0;
bank.questions.forEach((x, n) => {
  const e = topicMap.math?.[x.topic == null ? 'undefined' : x.topic];
  const target = e ? e.target : 'UNMAPPED';
  const t = tosByName.get(target);
  if (!t) {
    inc(dropped.byTarget, target);
    dropped.items.push({ id: x.id ?? null, topic: x.topic ?? null, target, question: String(x.question).slice(0, 100) });
    return;
  }
  if (x.tos && x.tos.target !== target) topicMapDisagrees++;
  const eff = effective(x);
  const r = {
    n, id: String(x.id), q: x.question, ...eff, topic: t.name, code: t.code, tosArea: t.group,
    bloom: mapBloom(x.bloom), difficulty: mapDifficulty(x.difficulty),
    quarantine: [], review: [],
  };
  const f = flagsFor(r);
  r.quarantine.push(...f.quarantine); r.review.push(...f.review);
  if (queued.has(`${x.id}\u0000${x.question}`)) r.review.push('converter-flag');
  if (e.confidence !== 'exact' && e.confidence !== 'case-or-and-variant') r.review.push('topic-not-exact');
  if (r.bloom === null) r.review.push('unknown-bloom');
  if (r.difficulty === null) r.review.push('unknown-difficulty');
  recs.push(r);
});

// ---- 2. duplicates, ids, statuses
const dup = applyDuplicates(recs);
assignIds(recs);
recs.forEach((r) => { r.status = statusOf(r); });

// ---- 3. rows in the app schema, grouped by topic
const row = (r) => ({
  id: r.finalId, category: 'Math Major', topic: r.topic, tosArea: r.tosArea, skill: '',
  q: r.q, options: r.options, answer: r.answer, why: r.why,
  bloom: r.bloom, difficulty: r.difficulty, status: r.status, source: SOURCE,
});
const byTopic = new Map(TOS.map((t) => [t.name, []]));
recs.forEach((r) => byTopic.get(r.topic).push(r));

fs.rmSync(DIR, { recursive: true, force: true });
fs.mkdirSync(DIR, { recursive: true });
const sizes = [];
const topics = [];
const totals = { live: 0, review: 0, quarantine: 0, all: 0 };
for (const t of TOS) {
  const list = byTopic.get(t.name);
  const c = { live: 0, review: 0, quarantine: 0 };
  list.forEach((r) => c[r.status]++);
  const file = `${slug(t.name)}.json`;
  const body = '[\n' + list.map((r) => JSON.stringify(row(r))).join(',\n') + '\n]\n';
  fs.writeFileSync(path.join(DIR, file), body);
  sizes.push({ file: `src/lib/data/math-major/${file}`, bytes: Buffer.byteLength(body) });
  topics.push({ code: t.code, topic: t.name, tosArea: t.group, file, ...c });
  for (const k of Object.keys(c)) totals[k] += c[k];
  totals.all += list.length;
}
const index = {
  category: 'Math Major', source: SOURCE, note: 'Counts only. Open a topic file to read its questions. Generated by tools/build-bank.mjs.',
  totals, dropped: { OUT_OF_TOS: dropped.byTarget.OUT_OF_TOS || 0, UNMAPPED: dropped.byTarget.UNMAPPED || 0, other: Object.entries(dropped.byTarget).filter(([k]) => k !== 'OUT_OF_TOS' && k !== 'UNMAPPED').reduce((a, [, v]) => a + v, 0) },
  topics,
};
const indexBody = JSON.stringify(index, null, 1) + '\n';
fs.writeFileSync(path.join(DIR, 'index.json'), indexBody);
sizes.push({ file: 'src/lib/data/math-major/index.json', bytes: Buffer.byteLength(indexBody) });

// ---- 4. id map (proven only) and the rest
const { map, rest } = buildIdMap(recs);
const idMapPath = path.join(DATA, 'id-map.json');
fs.rmSync(idMapPath, { force: true });
if (Object.keys(map).length) {
  const body = JSON.stringify(map, null, 1) + '\n';
  fs.writeFileSync(idMapPath, body);
  sizes.push({ file: 'src/lib/data/id-map.json', bytes: Buffer.byteLength(body) });
}
const unmappedIds = {
  note: 'Old math-major-### ids WITHOUT a proven qb-... target. Proof = identical normalised stem and choices, same correct answer, and the old id belongs to exactly one question. Nothing here is guessed.',
  mapped: Object.keys(map).length,
  counts: { 'kept-same-id': rest['kept-same-id'].length, 'ambiguous-shared-id': Object.keys(rest['ambiguous-shared-id']).length, 'duplicate-of-non-qb': Object.keys(rest['duplicate-of-non-qb']).length },
  reasons: {
    'kept-same-id': 'No qb- twin was proven. The id is still in the app data unchanged, so old progress under it still resolves.',
    'ambiguous-shared-id': 'The same id was used by different questions in the source, so nobody can tell which one old progress meant. Each row was renamed <id>.1, <id>.2 ... (value = new ids).',
    'duplicate-of-non-qb': 'Retired as an exact duplicate, but the live copy has a non-qb id (value = that id). Not written to id-map.json because the brief maps to qb- ids only.',
  },
  items: rest,
  notInThisBank: 'Old ids that never appear in this bank cannot be listed; there is no data to prove anything about them.',
};
fs.writeFileSync(path.join(OUT, 'unmapped-ids.json'), JSON.stringify(unmappedIds, null, 1) + '\n');

// ---- 5. unmapped topics (dropped from the app) + labels seen only in other stores
const otherLabels = Object.entries(topicMap.math)
  .filter(([, e]) => !tosByName.has(e.target))
  .map(([label, e]) => ({ label: label === 'undefined' ? '(no topic)' : label, target: e.target, itemsInAllStores: e.count ?? 0, itemsInThisBank: e.inBank ?? 0, note: e.note ?? null }));
fs.writeFileSync(path.join(OUT, 'unmapped-topics.json'), JSON.stringify({
  note: 'Math rows from the converted bank whose topic is OUT_OF_TOS or UNMAPPED. They are NOT written to the app.',
  droppedFromThisBank: dropped.items.length, byTarget: dropped.byTarget, items: dropped.items,
  labelsInOtherStores: otherLabels,
}, null, 1) + '\n');

// ---- 6. status report: why each non-live row is not live (keeps reasons out of the app data)
const reasons = {};
recs.forEach((r) => { [...r.quarantine, ...r.review].forEach((k) => inc(reasons, k)); });
fs.writeFileSync(path.join(OUT, 'bank-status-report.json'), JSON.stringify({
  totals, reasonCounts: reasons,
  duplicates: dup, topicMapDisagreements: topicMapDisagrees,
  idsRenamed: recs.filter((r) => r.idChange).length,
  items: recs.filter((r) => r.status !== 'live').map((r) => ({
    id: r.finalId, originalId: r.id, topic: r.topic, status: r.status,
    quarantine: r.quarantine, review: r.review, duplicateOf: r.dupOf != null ? recs[r.dupOf].finalId : undefined,
  })),
}, null, 1) + '\n');

// ---- 7. checks
const sumIdx = topics.reduce((a, t) => a + t.live + t.review + t.quarantine, 0);
if (sumIdx !== bank.questions.length - dropped.items.length) throw new Error(`index total ${sumIdx} != bank ${bank.questions.length} - dropped ${dropped.items.length}`);
const seen = new Set();
for (const r of recs) {
  if (seen.has(r.finalId)) throw new Error(`duplicate id ${r.finalId}`);
  seen.add(r.finalId);
  if (r.status === 'live' && (r.options.length !== 4 || !Number.isInteger(r.answer) || r.answer < 0 || r.answer > 3)) throw new Error(`live row not valid: ${r.finalId}`);
}
for (const [old, nu] of Object.entries(map)) if (!seen.has(nu)) throw new Error(`id-map target missing: ${old} -> ${nu}`);

// ---- 8. table
const kb = (b) => (b / 1024).toFixed(1);
const pad = (s, n, left) => (left ? String(s).padStart(n) : String(s).padEnd(n));
console.log('\n' + pad('Topic', 38) + pad('live', 7, 1) + pad('review', 8, 1) + pad('quar.', 7, 1) + pad('total', 7, 1) + pad('KB', 9, 1));
for (const t of topics) {
  const s = sizes.find((z) => z.file.endsWith('/' + t.file));
  console.log(pad(`${t.code} ${t.topic}`, 38) + pad(t.live, 7, 1) + pad(t.review, 8, 1) + pad(t.quarantine, 7, 1) + pad(t.live + t.review + t.quarantine, 7, 1) + pad(kb(s.bytes) + (s.bytes > 300 * 1024 ? ' !' : ''), 9, 1));
}
console.log(pad('TOTAL', 38) + pad(totals.live, 7, 1) + pad(totals.review, 8, 1) + pad(totals.quarantine, 7, 1) + pad(totals.all, 7, 1) + pad(kb(sizes.filter((z) => z.file.includes('math-major/') && !z.file.endsWith('index.json')).reduce((a, z) => a + z.bytes, 0)), 9, 1));
console.log('\nOther files:');
for (const z of sizes.filter((z) => !z.file.match(/math-major\/(?!index)/))) console.log(`  ${pad(z.file, 44)} ${kb(z.bytes)} KB`);
const big = sizes.filter((z) => z.bytes > 300 * 1024);
console.log(big.length ? `\nOVER 300 KB: ${big.map((z) => z.file).join(', ')}` : '\nNo file over 300 KB.');
console.log(`\nConverted rows ${bank.questions.length}, dropped (OUT_OF_TOS/UNMAPPED) ${dropped.items.length}, written ${totals.all}.`);
console.log(`Duplicates: ${dup.groups} groups, ${dup.retired} copies retired, ${dup.conflicts} answer-conflict groups. Ids renamed (shared ids): ${recs.filter((r) => r.idChange).length}. id-map entries: ${Object.keys(map).length}.`);
console.log('Reasons:', JSON.stringify(reasons));
